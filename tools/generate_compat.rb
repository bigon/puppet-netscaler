#!/usr/bin/env ruby
# frozen_string_literal: true

# Render the netscaler_* compatibility types as static Resource API type files
# (so puppet-strings can document them) from
# lib/puppet_x/netscaler/compat_definitions.rb.
#
#   ruby tools/generate_compat.rb <module root>
#
# compat_definitions.rb itself was derived once from the puppetlabs-netscaler
# 1.x sources and is maintained by hand from now on.
$LOAD_PATH.unshift(File.expand_path('../lib', __dir__))
require 'puppet'
require 'puppet_x/netscaler/compat_provider'

module CompatGenerator
  module_function

  def literal(obj, indent = 0)
    pad = ' ' * (indent + 2)
    case obj
    when Hash
      inner = obj.map { |k, v| "#{pad}#{k}: #{literal(v, indent + 2)}," }
      "{\n#{inner.join("\n")}\n#{' ' * indent}}"
    when Array
      "[#{obj.map { |v| literal(v, indent) }.join(', ')}]"
    else
      obj.inspect
    end
  end

  def render(type_name)
    definition = PuppetX::Netscaler::Compat.definition(type_name)
    definition_attributes = definition[:attributes]
    docs = definition.delete(:docs)
    <<~RUBY
      # frozen_string_literal: true

      # This file is generated by tools/generate_compat.rb from
      # lib/puppet_x/netscaler/compat_definitions.rb, derived from
      # puppetlabs-netscaler (Copyright 2014 Puppet, Inc., Apache-2.0). Do not edit.
      require 'puppet/resource_api'

      Puppet::ResourceApi.register_type(
        name: #{definition.delete(:name).inspect},
        docs: <<~EOS,
      #{docs.gsub(%r{^}, '    ').gsub(%r{^ +$}, '')}
        EOS
        features: #{literal(definition.delete(:features))},
        attributes: #{literal(definition.delete(:attributes), 2)},
      )
      #{[render_autorequires(type_name), render_sensitive(type_name, definition_attributes)].reject(&:empty?).join("\n")}
    RUBY
  end

  # Autorequire the netscaler_* and nitro_* types of each referenced entity,
  # named either by an attribute or by a part of the title
  def render_autorequires(type_name)
    compat = PuppetX::Netscaler::COMPAT.fetch(type_name)
    deps = compat.fetch(:autorequire, {})
    return '' if deps.empty?

    lines = ['', '# Ordering, as puppetlabs-netscaler declared it', "type = Puppet::Type.type(:#{type_name})"]
    deps.each do |nitro, source|
      value = if source.is_a?(Symbol)
                "self[:#{source}]"
              else
                "self[:name].to_s[%r{#{compat[:title_pattern].source}}, '#{source}']"
              end
      %W[netscaler_#{nitro} nitro_#{nitro}].each do |target|
        lines << "type.autorequire(:#{target}) { #{value} }"
      end
    end
    lines.join("\n")
  end

  # Secrets: Puppet redacts the events of the properties, also when the
  # manifest passes a plain String. Parameters never show up in events, so
  # Puppet is not asked to redact them (it would warn on every run).
  def render_sensitive(type_name, attributes)
    compat = PuppetX::Netscaler::COMPAT.fetch(type_name)
    secrets = compat[:attributes].select { |_n, a| PuppetX::Netscaler::Compat.sensitive?(compat, a) }.keys.sort
    return '' if secrets.empty?

    params, props = secrets.partition { |n| attributes[n][:behaviour] == :parameter }
    [
      '',
      '# Redact the secrets in events, also when given as a plain String',
      "Puppet::Type.type(:#{type_name}).class_eval do",
      '  def set_sensitive_parameters(sensitive_parameters)',
      "    super((sensitive_parameters - %i[#{params.join(' ')}]) | %i[#{props.join(' ')}].select { |n| parameter(n) })",
      '  end',
      'end',
    ].join("\n")
  end

  def run(root)
    PuppetX::Netscaler::COMPAT.each_key do |name|
      File.write(File.join(root, "lib/puppet/type/#{name}.rb"), render(name))
    end
  end
end

if $PROGRAM_NAME == __FILE__
  CompatGenerator.run(ARGV.fetch(0, File.expand_path('..', __dir__)))
  puts "Generated #{PuppetX::Netscaler::COMPAT.size} compat types"
end
